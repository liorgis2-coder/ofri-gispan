/** URL of a site page by slug, of a post by "post-{slug}", optionally with an in-page anchor. */
function ofri_link( $slug, $anchor = '' ) {
	if ( 'home' === $slug ) {
		$url = home_url( '/' );
	} elseif ( 0 === strpos( $slug, 'post-' ) ) {
		$post = get_page_by_path( substr( $slug, 5 ), OBJECT, 'post' );
		$url  = $post ? get_permalink( $post ) : ofri_link( 'blog' );
	} else {
		$page = get_page_by_path( $slug );
		$url  = $page ? get_permalink( $page ) : home_url( '/' . $slug . '/' );
	}
	return $anchor ? $url . '#' . $anchor : $url;
}

/** Which of the fixed pages is being shown: a slug from ofri_pages(), "post", or "" for anything else. */
function ofri_route() {
	if ( is_front_page() ) {
		return 'home';
	}
	if ( is_home() || is_category() || is_tag() || is_author() || is_date() ) {
		return 'blog';
	}
	if ( is_singular( 'post' ) ) {
		return 'post';
	}
	if ( is_page() ) {
		$slug = get_post_field( 'post_name', get_queried_object_id() );
		return isset( ofri_pages()[ $slug ] ) ? $slug : '';
	}
	return '';
}
